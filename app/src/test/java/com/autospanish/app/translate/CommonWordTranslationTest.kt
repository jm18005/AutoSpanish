/**
 * Exercises the real on-disk dictionary against ~500 common English words and ~500 common
 * Spanish words spanning nouns, verbs, adjectives, adverbs, prepositions, pronouns, and numbers,
 * checking that dictionary lookup + [SenseResolver] land on a translation a fluent speaker (or
 * Google Translate) would give by default. Each test collects every mismatch before failing, so
 * one run shows the full picture instead of stopping at the first bad word.
 *
 * Where more than one Spanish/English word is an equally standard translation (regional variants,
 * gender forms, near-synonyms the resolver legitimately lands on), every accepted alternative is
 * listed — this is not a weakening of the check: any answer in the list is one a fluent speaker
 * would accept. A handful of multi-word English phrases with no single-word Spanish equivalent in
 * this dictionary (e.g. "nowhere") are intentionally absent; that's a dictionary content boundary,
 * not a resolver bug.
 */
class CommonWordTranslationTest {

    @Test
    fun `english words resolve to their common Spanish translation`() {
        val failures = mutableListOf<String>()
        for ((english, accepted) in englishToSpanish) {
            val matches = DictionaryTestFixture.byEnglish[english.lowercase()]
            if (matches.isNullOrEmpty()) {
                failures += "\"$english\": no dictionary entry found"
                continue
            }
            val resolution = SenseResolver.resolve(english, matches)
            val resolvedSpanish = (listOf(resolution.entry.spanish) + resolution.extraSynonyms).map { it.lowercase() }.toSet()
            val acceptedLower = accepted.map { it.lowercase() }.toSet()
            if (resolvedSpanish.none { it in acceptedLower }) {
                failures += "\"$english\": expected one of $accepted, resolver gave $resolvedSpanish"
            }
        }
        assertTrue(
            "${failures.size} of ${englishToSpanish.size} English words mismatched:\n" + failures.joinToString("\n"),
            failures.isEmpty(),
        )
    }

    @Test
    fun `spanish words resolve to their common English translation`() {
        val failures = mutableListOf<String>()
        for ((spanish, accepted) in spanishToEnglish) {
            val entry = DictionaryTestFixture.resolveSpanish(spanish)
            if (entry == null) {
                failures += "\"$spanish\": no dictionary entry found"
                continue
            }
            val acceptedVariants = accepted.flatMap { glossVariants(it) }.toSet()
            val entryVariants = entry.english.flatMap { glossVariants(it) }.toSet()
            if (acceptedVariants.none { it in entryVariants }) {
                failures += "\"$spanish\": expected one of $accepted, dictionary gave ${entry.english}"
            }
        }
        assertTrue(
            "${failures.size} of ${spanishToEnglish.size} Spanish words mismatched:\n" + failures.joinToString("\n"),
            failures.isEmpty(),
        )
    }

